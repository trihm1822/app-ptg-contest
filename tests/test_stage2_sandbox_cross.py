"""Cross-stage integration test: Verifying Stage 2 generated C++ code inside Stage 1 Docker Sandbox."""

import subprocess
import tempfile
from pathlib import Path

import pytest
from ptg.core.code_generator import CodeGenerator
from ptg.core.runner import IsolatedRunner
from ptg.integrations.llm.mock import MockLLMProvider
from ptg.models.runner import Verdict


def is_docker_running() -> bool:
    """Check if Docker daemon is accessible."""
    try:
        res = subprocess.run(["docker", "info"], capture_output=True, timeout=3)
        return res.returncode == 0
    except Exception:
        return False


pytestmark = pytest.mark.skipif(not is_docker_running(), reason="Docker daemon is not running")


@pytest.fixture
def runner():
    """Isolated Docker sandbox runner fixture."""
    return IsolatedRunner()


def test_generated_cpp_artifacts_in_docker_sandbox(runner):
    """Test that all 4 C++ artifacts generated by CodeGenerator compile and execute correctly in Docker Sandbox."""
    with tempfile.TemporaryDirectory(prefix="ptg_cross_stage_") as tmp_dir:
        workspace = Path(tmp_dir)

        # 1. Generate code using CodeGenerator with MockLLMProvider
        problem_file = workspace / "test_prob.md"
        problem_file.write_text("# Two Sum\nFind two numbers summing to target.", encoding="utf-8")

        artifacts_dir = workspace / "artifacts"
        code_gen = CodeGenerator(provider=MockLLMProvider())
        _, files = code_gen.generate_from_file(
            problem_path=problem_file,
            output_dir=artifacts_dir,
            use_cache=False,
            use_mock=True,
        )

        # 2. Compile brute.cpp in Docker sandbox
        brute_code = files["brute.cpp"].read_text(encoding="utf-8")
        comp_brute = runner.compile(brute_code, binary_name="brute", workspace_dir=workspace)
        assert comp_brute.success is True, f"brute.cpp failed to compile: {comp_brute.error_message}"

        # 3. Compile optimized.cpp in Docker sandbox
        opt_code = files["optimized.cpp"].read_text(encoding="utf-8")
        comp_opt = runner.compile(opt_code, binary_name="optimized", workspace_dir=workspace)
        assert comp_opt.success is True, f"optimized.cpp failed to compile: {comp_opt.error_message}"

        # 4. Compile generator.cpp in Docker sandbox
        gen_code = files["generator.cpp"].read_text(encoding="utf-8")
        comp_gen = runner.compile(gen_code, binary_name="generator", workspace_dir=workspace)
        assert comp_gen.success is True, f"generator.cpp failed to compile: {comp_gen.error_message}"

        # 5. Compile validator.cpp in Docker sandbox
        val_code = files["validator.cpp"].read_text(encoding="utf-8")
        comp_val = runner.compile(val_code, binary_name="validator", workspace_dir=workspace)
        assert comp_val.success is True, f"validator.cpp failed to compile: {comp_val.error_message}"

        # 6. Execute Generator (seed=12345, subtask=1)
        gen_res = runner.execute("generator", workspace_dir=workspace, args=["12345", "1"])
        assert gen_res.verdict == Verdict.OK
        assert len(gen_res.stdout.strip()) > 0
        input_data = gen_res.stdout

        # 7. Execute Validator with generated input
        val_res = runner.execute("validator", workspace_dir=workspace, stdin_data=input_data)
        assert val_res.verdict == Verdict.OK

        # 8. Execute Brute solution with generated input
        brute_res = runner.execute("brute", workspace_dir=workspace, stdin_data=input_data)
        assert brute_res.verdict == Verdict.OK
        assert len(brute_res.stdout.strip()) > 0

        # 9. Execute Optimized solution with generated input
        opt_res = runner.execute("optimized", workspace_dir=workspace, stdin_data=input_data)
        assert opt_res.verdict == Verdict.OK
        assert len(opt_res.stdout.strip()) > 0

        # 10. Cross-compare outputs
        assert brute_res.stdout.strip() == opt_res.stdout.strip(), (
            f"Outputs mismatch! Brute: '{brute_res.stdout}', Opt: '{opt_res.stdout}'"
        )
